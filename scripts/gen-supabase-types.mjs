#!/usr/bin/env node
/**
 * Generates `src/integrations/supabase/external-types.ts` from the live
 * external Supabase project's PostgREST OpenAPI description.
 *
 * Usage:  SERVICE_ROLE_KEY=... node scripts/gen-supabase-types.mjs
 *
 * The service-role key is only used here (build/CLI time) — never in app code.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const URL_ = process.env.EXTERNAL_SUPABASE_URL || 'https://quvqjctlskmqeyhognvd.supabase.co';
const KEY = process.env.SERVICE_ROLE_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!KEY) {
  console.error('Missing SERVICE_ROLE_KEY env var.');
  process.exit(1);
}

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/integrations/supabase/external-types.ts');

function tsType(schema) {
  if (!schema) return 'unknown';
  if (schema.type === 'array') return `${tsType(schema.items)}[]`;
  switch (schema.format) {
    case 'json':
    case 'jsonb':
      return 'Json';
    case 'integer':
    case 'bigint':
    case 'smallint':
    case 'numeric':
    case 'double precision':
    case 'real':
      return 'number';
    case 'boolean':
      return 'boolean';
    default:
      break;
  }
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'object') return 'Json';
  return 'string';
}

const res = await fetch(`${URL_}/rest/v1/`, {
  headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, Accept: 'application/openapi+json' },
});
if (!res.ok) {
  console.error('Failed to fetch schema:', res.status, await res.text());
  process.exit(1);
}
const spec = await res.json();

const tables = Object.entries(spec.definitions || {}).sort(([a], [b]) => a.localeCompare(b));
const rpcs = Object.entries(spec.paths || {})
  .filter(([p]) => p.startsWith('/rpc/'))
  .map(([p, v]) => [p.slice(5), v.post?.parameters?.find((x) => x.in === 'body')?.schema || { properties: {}, required: [] }])
  .sort(([a], [b]) => a.localeCompare(b));

let out = `// AUTO-GENERATED by scripts/gen-supabase-types.mjs — do not edit by hand.
// Source: external Supabase project PostgREST schema (${URL_}).
// Regenerate with: SERVICE_ROLE_KEY=... node scripts/gen-supabase-types.mjs

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type ExternalDatabase = {
  public: {
    Tables: {
`;

for (const [name, def] of tables) {
  const props = Object.entries(def.properties || {}).sort(([a], [b]) => a.localeCompare(b));
  const required = new Set(def.required || []);
  const row = props
    .map(([k, s]) => `        ${JSON.stringify(k)}: ${tsType(s)}${required.has(k) ? '' : ' | null'};`)
    .join('\n');
  const insert = props
    .map(([k, s]) => {
      const optional = !required.has(k) || s.default !== undefined;
      return `        ${JSON.stringify(k)}${optional ? '?' : ''}: ${tsType(s)}${required.has(k) ? '' : ' | null'};`;
    })
    .join('\n');
  const update = props
    .map(([k, s]) => `        ${JSON.stringify(k)}?: ${tsType(s)}${required.has(k) ? '' : ' | null'};`)
    .join('\n');
  out += `      ${JSON.stringify(name)}: {
        Row: {
${row}
        };
        Insert: {
${insert}
        };
        Update: {
${update}
        };
        Relationships: [];
      };
`;
}

out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;

for (const [name, schema] of rpcs) {
  const props = Object.entries(schema.properties || {}).sort(([a], [b]) => a.localeCompare(b));
  const required = new Set(schema.required || []);
  const args = props.length
    ? props.map(([k, s]) => `        ${JSON.stringify(k)}${required.has(k) ? '' : '?'}: ${tsType(s)};`).join('\n')
    : null;
  out += `      ${JSON.stringify(name)}: {
        Args: ${args ? `{\n${args}\n        }` : 'Record<PropertyKey, never>'};
        Returns: Json;
      };
`;
}

out += `    };
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
};

export type ExternalTables<T extends keyof ExternalDatabase['public']['Tables']> =
  ExternalDatabase['public']['Tables'][T]['Row'];
`;

writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${tables.length} tables, ${rpcs.length} functions.`);
